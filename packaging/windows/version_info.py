"""Generates a PyInstaller Windows version-resource file from pyproject.toml.

PyInstaller's ``EXE(..., version=...)`` wants a path to a text file
containing a single Python expression that builds a ``VSVersionInfo``
object -- the same format ``pyi-grab_version`` produces, and the format
``PyInstaller.utils.win32.versioninfo.load_version_info_from_text_file``
evaluates with ``VSVersionInfo``/``FixedFileInfo``/``StringFileInfo``/
``StringTable``/``StringStruct``/``VarFileInfo``/``VarStruct`` already bound
in its namespace. This module renders that file directly from the
project's version on every Windows build (called from
``packaging/pyinstaller/auto_text_typer.spec``) instead of checking in a
hand-maintained copy that could drift out of sync with ``pyproject.toml``.

Also runnable standalone, to inspect (or regenerate) the file on its own:

    python packaging/windows/version_info.py [output_path]
"""
from __future__ import annotations

import datetime
import sys
import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "build" / "windows_version_info.txt"

COMPANY_NAME = "Braxton Gorman"
FILE_DESCRIPTION = "Auto Text Typer"
PRODUCT_NAME = "Auto Text Typer"
ORIGINAL_FILENAME = "AutoTextTyper.exe"

# VOS_NT_WINDOWS32 (0x00040000 | 0x00000004) and VFT_APP -- the combination
# PyInstaller's own `pyi-grab_version` uses for a normal windowed exe.
_OS_NT_WINDOWS32 = 0x40004
_VFT_APP = 0x1


def _version_tuple(version: str) -> tuple[int, int, int, int]:
    """Parse a 'X.Y.Z[...]' string into the 4-int tuple Windows wants.

    Non-numeric or missing components (a pre-release suffix, a short
    "0.1" version, ...) fall back to 0 rather than raising: this only
    feeds a display/version resource, not anything semantically
    load-bearing.
    """
    parts = version.split(".")[:4]
    nums: list[int] = []
    for part in parts:
        digits = ""
        for ch in part:
            if not ch.isdigit():
                break
            digits += ch
        nums.append(int(digits) if digits else 0)
    while len(nums) < 4:
        nums.append(0)
    return tuple(nums[:4])  # type: ignore[return-value]


def read_version() -> str:
    with open(REPO_ROOT / "pyproject.toml", "rb") as f:
        data = tomllib.load(f)
    return data["project"]["version"]


def render_version_file(version: str) -> str:
    file_vers = _version_tuple(version)
    legal_copyright = f"Copyright (c) {datetime.date.today().year} {COMPANY_NAME}"

    # This text is not merely data: PyInstaller evaluates it as a Python
    # expression with the VSVersionInfo/... names already in scope, so it
    # must stay valid Python literal syntax, not a string template.
    return f"""# UTF-8
#
# Generated by packaging/windows/version_info.py from pyproject.toml
# (currently version {version}) -- do not hand-edit, re-run the generator
# instead. Consumed by PyInstaller's EXE(version=...) at build time.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={file_vers!r},
    prodvers={file_vers!r},
    mask=0x3f,
    flags=0x0,
    OS={_OS_NT_WINDOWS32!r},
    fileType={_VFT_APP!r},
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          "040904B0",
          [
            StringStruct("CompanyName", {COMPANY_NAME!r}),
            StringStruct("FileDescription", {FILE_DESCRIPTION!r}),
            StringStruct("FileVersion", {version!r}),
            StringStruct("InternalName", {ORIGINAL_FILENAME!r}),
            StringStruct("LegalCopyright", {legal_copyright!r}),
            StringStruct("OriginalFilename", {ORIGINAL_FILENAME!r}),
            StringStruct("ProductName", {PRODUCT_NAME!r}),
            StringStruct("ProductVersion", {version!r}),
          ],
        )
      ],
    ),
    VarFileInfo([VarStruct("Translation", [1033, 1200])]),
  ],
)
"""


def write_version_file(version: str, output_path: str | Path = DEFAULT_OUTPUT) -> Path:
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(render_version_file(version), encoding="utf-8")
    return output_path


def main(argv: list[str]) -> int:
    version = read_version()
    output = Path(argv[0]) if argv else DEFAULT_OUTPUT
    write_version_file(version, output)
    print(f"wrote {output} for version {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
