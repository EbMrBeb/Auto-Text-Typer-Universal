def test_no_sentence_blames_the_editor_for_something_the_app_chose_not_to_set_up():
    # Word has list shortcuts and Windows Google Docs has a justify shortcut that opens the
    # browser's developer tools, so "has no shortcut" would be false. What is always true is
    # that none is set up.
    message = '2 bullet-list paragraphs typed as plain text with a "•" marker (no bullet-list shortcut in this keymap)'
    sentence = explain_adaptation_warning(message, "Microsoft Word")
    assert "Microsoft Word has no" not in sentence
    assert "is set up for Microsoft Word" in sentence


def test_the_editor_is_named_in_the_sentence():
    message = "1 run lost bold formatting (no bold shortcut in this keymap)"
    assert "TextEdit" in explain_adaptation_warning(message, "TextEdit")
    assert "a plain-text field" in explain_adaptation_warning(message, "a plain-text field")


def test_an_adaptation_message_this_module_does_not_know_loses_its_jargon_but_not_its_facts():
    message = "4 widgets typed as gadgets (no widget shortcut in this keymap)"
    plain = explain_adaptation_warning(message, "Microsoft Word")
    assert plain == "4 widgets typed as gadgets (no widget shortcut set up for Microsoft Word)."
    assert "keymap" not in plain
    assert not is_known_adaptation_warning(message)


def _every_kind_of_loss() -> Document:
    """A document that triggers every fallback ``adapt_document`` has."""
    styled = lambda text, *styles: Run(text, frozenset(styles))  # noqa: E731
    return Document(
        (
            Paragraph((Run("Title"),), style=ParagraphStyle.TITLE),
            Paragraph((Run("Subtitle"),), style=ParagraphStyle.SUBTITLE),
            Paragraph((Run("Heading one"),), style=ParagraphStyle.HEADING_1),
            Paragraph((Run("Heading two"),), style=ParagraphStyle.HEADING_2),
            Paragraph((Run("Heading three"),), style=ParagraphStyle.HEADING_3),
            Paragraph((Run("Centered"),), alignment=Alignment.CENTER),
            Paragraph((Run("Right"),), alignment=Alignment.RIGHT),
            Paragraph((Run("Justified"),), alignment=Alignment.JUSTIFIED),
            Paragraph(
                (
                    styled("bold", TextStyle.BOLD),
                    styled("italic", TextStyle.ITALIC),
                    styled("underline", TextStyle.UNDERLINE),
                    styled("strike", TextStyle.STRIKETHROUGH),
                )
            ),
            Paragraph((Run("bullet"),), list_kind=ListKind.BULLET),
            Paragraph((Run("number"),), list_kind=ListKind.NUMBERED),
        )
    )


def _every_editor():
    for os_ in OperatingSystem:
        for target in targets.targets_for(os_):
            yield pytest.param(os_, target, id=f"{os_.value}-{target.id}")


@pytest.mark.parametrize(("os_", "target"), list(_every_editor()))
def test_every_message_adapt_document_gives_for_a_shipped_editor_is_recognised(os_, target):
    keymap = targets.keymap_for(target.id, os_)
    fixture_document, _report = load_document(str(FIXTURE))
    for document in (fixture_document, _every_kind_of_loss()):
        _adapted, messages = adapt_document(document, keymap)
        for message in messages:
            assert is_known_adaptation_warning(message), message
            plain = explain_adaptation_warning(message, editor_phrase(target))
            assert plain != message
            assert editor_phrase(target) in plain
            assert plain.endswith(".")
            assert not any(word in plain for word in _JARGON), plain


def test_every_message_adapt_document_gives_when_any_one_shortcut_is_missing_is_recognised():
    """Take each shortcut out of a full keymap in turn: every fallback the library has fires."""
    document = _every_kind_of_loss()
    produced: list[str] = []
    for op in FormatOp:
        if op is FormatOp.CLEAR_FORMATTING:
            continue  # a keymap must always have it
        keymap = {o: chord for o, chord in GOOGLE_DOCS_MAC.items() if o is not op}
        _adapted, messages = adapt_document(document, keymap)
        produced.extend(messages)
    assert [m for m in set(produced) if not is_known_adaptation_warning(m)] == []
    from auto_essay_typer.gui.document_warnings import _parse_adaptation

    assert {_parse_adaptation(m).kind for m in produced} == {
        "substitution",
        "heading",
        "alignment",
        "style",
        "bullets",
        "numbered",
    }, "removing single shortcuts should reach every kind of fallback"


def test_the_templates_the_tests_reach_cover_every_kind_this_module_words():
    from auto_essay_typer.gui.document_warnings import _parse_adaptation

    plain_text = targets.keymap_for("plain-text", OperatingSystem.MACOS)
    _adapted, messages = adapt_document(_every_kind_of_loss(), plain_text)
    kinds = {_parse_adaptation(m).kind for m in messages}
    assert kinds == {"substitution", "heading", "alignment", "style", "bullets", "numbered"}


# --- a title that cannot be a heading either -----------------------------------------------------------------------


def _warnings_for(document: Document, target_id: str) -> tuple[str, ...]:
    target = targets.get_target(target_id)
    _adapted, messages = adapt_document(document, targets.keymap_for(target_id, OperatingSystem.MACOS))
    return explain_warnings([], messages, editor_phrase(target))


def _titles_and_headings(*, real_heading_1: int, real_heading_2: int = 0) -> Document:
    paragraphs = [Paragraph((Run("The title"),), style=ParagraphStyle.TITLE)]
    paragraphs += [Paragraph((Run(f"Heading {n}"),), style=ParagraphStyle.HEADING_1) for n in range(real_heading_1)]
    paragraphs += [Paragraph((Run("The subtitle"),), style=ParagraphStyle.SUBTITLE)]
    paragraphs += [Paragraph((Run(f"Second {n}"),), style=ParagraphStyle.HEADING_2) for n in range(real_heading_2)]
    return Document(tuple(paragraphs))


def test_a_title_in_an_editor_with_no_headings_is_said_to_become_body_text_not_heading_1():
    lines = _warnings_for(_titles_and_headings(real_heading_1=0), "plain-text")
    assert lines == (
        "1 title will be typed as ordinary text, because no title or Heading 1 shortcut is set up for "
        "a plain-text field.",
        "1 subtitle will be typed as ordinary text, because no subtitle or Heading 2 shortcut is set up "
        "for a plain-text field.",
    )


def test_only_the_real_headings_are_left_in_the_heading_line_once_the_titles_are_taken_out():
    # Raw library messages say "2 Heading 1 paragraphs ...": one of them is the title.
    document = _titles_and_headings(real_heading_1=1, real_heading_2=3)
    _adapted, raw = adapt_document(document, targets.keymap_for("plain-text", OperatingSystem.MACOS))
    assert any(m.startswith("2 Heading 1 paragraphs") for m in raw)
    assert any(m.startswith("4 Heading 2 paragraphs") for m in raw)

    lines = _warnings_for(document, "plain-text")

    assert "1 Heading 1 paragraph will be typed as ordinary text, because no Heading 1 shortcut is set up for a plain-text field." in lines
    assert "3 Heading 2 paragraphs will be typed as ordinary text, because no Heading 2 shortcut is set up for a plain-text field." in lines
    assert not any("2 Heading 1" in line or "4 Heading 2" in line for line in lines)
    assert len(lines) == 4  # title, subtitle, Heading 1s, Heading 2s


def test_the_bold_stand_in_is_carried_into_the_joined_line():
    lines = _warnings_for(_titles_and_headings(real_heading_1=0), "textedit")
    assert lines[0].startswith("1 title will be typed as bold text, because no title or Heading 1 shortcut")


def test_a_title_that_can_become_heading_1_keeps_its_own_line_and_nothing_is_joined():
    lines = _warnings_for(_titles_and_headings(real_heading_1=2), "google-docs")
    assert lines == (
        "1 title will be typed as Heading 1, because no title shortcut is set up for Google Docs.",
        "1 subtitle will be typed as Heading 2, because no subtitle shortcut is set up for Google Docs.",
    )


def test_titles_are_listed_before_subtitles_and_headings_before_alignment_text_and_lists():
    lines = _warnings_for(_every_kind_of_loss(), "plain-text")
    order = [
        next(i for i, line in enumerate(lines) if marker in line)
        for marker in (
            "title will be",
            "subtitle will be",
            "Heading 1 paragraph",
            "Heading 3 paragraph",
            "centered paragraph",
            "lose bold",
            "bulleted list",
            "numbered list",
        )
    ]
    assert order == sorted(order)


def test_a_joined_pair_is_not_mistaken_when_the_counts_do_not_add_up():
    """If a library change made the heading count smaller than the titles', nothing is invented."""
    lines = explain_warnings(
        [],
        [
            "3 Title paragraphs typed as Heading 1 (no Title shortcut in this keymap)",
            "1 Heading 1 paragraph typed as Normal (no Heading 1 shortcut in this keymap)",
        ],
        "TextEdit",
    )
    assert len(lines) == 2
    assert lines[0].startswith("3 titles will be typed as Heading 1")


# --- putting the panel's list together ----------------------------------------------------------------


def test_editor_phrase_calls_the_plain_text_fallback_a_field_and_others_by_name():
    assert editor_phrase(targets.get_target("plain-text")) == "a plain-text field"
    assert editor_phrase(targets.get_target("google-docs")) == "Google Docs"
    assert editor_phrase(targets.get_target("microsoft-word")) == "Microsoft Word"


def test_the_importers_warnings_come_first_then_the_editors():
    lines = explain_warnings(
        ["1 image not reproduced (dropped)"],
        ["1 run lost bold formatting (no bold shortcut in this keymap)"],
        "TextEdit",
    )
    assert len(lines) == 2
    assert "image" in lines[0]
    assert "bold" in lines[1] and "TextEdit" in lines[1]


def test_each_library_warning_is_one_line_when_nothing_needs_joining():
    importer = ["1 link typed as plain text", "2 images not reproduced (dropped)"]
    adaptation = [
        "1 Title paragraph typed as Heading 1 (no Title shortcut in this keymap)",
        "1 run lost italic formatting (no italic shortcut in this keymap)",
    ]
    assert len(explain_warnings(importer, adaptation, "Microsoft Word")) == 4


def test_unknown_messages_are_kept_and_listed_last():
    lines = explain_warnings(
        ["a brand new importer loss"],
        ["9 gizmos typed as gadgets (no gizmo shortcut in this keymap)", "1 run lost bold formatting (no bold shortcut in this keymap)"],
        "Microsoft Word",
    )
    assert lines[0] == "A brand new importer loss."
    assert lines[-1].startswith("9 gizmos typed as gadgets")
    assert "bold" in lines[1]


def test_identical_lines_are_listed_once():
    lines = explain_warnings(["1 link typed as plain text", "1 link typed as plain text"], [], "Google Docs")
    assert len(lines) == 1


def test_no_warnings_gives_an_empty_list():
    assert explain_warnings([], [], "Google Docs") == ()
