"""The plain-language wording of the "What will not be reproduced" panel.

These tests pin two things. The wording of each known library message, and --
because the wording is matched against the libraries' own strings -- that every
message the real importers and ``adapt_document`` can produce is *recognised* (not
merely given some sentence by the fallback), so a template added or reworded in a
library fails here instead of leaking jargon onto the screen. The inputs for that
second kind of test are generated by the libraries themselves rather than typed out.
"""

